// Compile-time checks: the generated JSON fits the frontend's types. A
// JSON import types its strings as string, so string unions ("admin" |
// "user") are widened to string here; any other difference (a field
// renamed, an object where the UI expects a string, a missing field) fails
// `tsc --noEmit`.
type Widen<T> = T extends string ? string : T extends (infer U)[] ? Widen<U>[] : T extends object ? { [K in keyof T]: Widen<T[K]> } : T;
