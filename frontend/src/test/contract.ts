/*
 * The backend's answers to a user who is not a cluster-admin, as the Go
 * handlers produce them: frontend/src/test/contract/*.json is generated by
 * pkg/api TestFrontendContract from the Go types (regenerate with
 * `go test ./pkg/api -run TestFrontendContract -update-contract`). Tests
 * build their fixtures from these, so a Go type the UI does not follow
 * fails here, not on a cluster.
 *
 * The JSON is assigned to the frontend's types below: a field the Go side
 * renamed or retyped fails `tsc --noEmit` (contract.test.ts also checks the
 * shapes at run time).
 */

/** The project the generated project fixtures are about. */
export const CONTRACT_PROJECT = "team-a";
/** The project whose generated reads all report problems. */
export const CONTRACT_DENIED_PROJECT = "team-denied";

const clone = <T,>(v: unknown): T => JSON.parse(JSON.stringify(v)) as T;

/** A fixture with its project renamed (the generated ones are about CONTRACT_PROJECT or CONTRACT_DENIED_PROJECT). */
function forProject<T>(v: unknown, from: string, project: string): T {
  return JSON.parse(JSON.stringify(v).split(from).join(project)) as T;
}

export const contract = {
  summary: (): ClusterSummary => clone<ClusterSummary>(summaryJson),
  operationUser: (): UserOperationStatus => clone<UserOperationStatus>(operationUserJson),
  permissionsUser: (): UserPermissions => clone<UserPermissions>(permissionsUserJson),
  permissionsAdmin: (): UserPermissions => clone<UserPermissions>(permissionsAdminJson),
  projectStatus: (project = CONTRACT_PROJECT): ProjectStatus => forProject<ProjectStatus>(projectStatusJson, CONTRACT_PROJECT, project),
  projectStatusProblems: (project = CONTRACT_DENIED_PROJECT): ProjectStatus => forProject<ProjectStatus>(projectStatusProblemsJson, CONTRACT_DENIED_PROJECT, project),
  playground: (project = CONTRACT_PROJECT): PlaygroundStatus => forProject<PlaygroundStatus>(playgroundJson, CONTRACT_PROJECT, project),
  playgroundProblem: (project = CONTRACT_DENIED_PROJECT): PlaygroundStatus => forProject<PlaygroundStatus>(playgroundProblemJson, CONTRACT_DENIED_PROJECT, project),
  mlflowSamples: (project = CONTRACT_PROJECT): MLflowSamplesStatus => forProject<MLflowSamplesStatus>(samplesJson, CONTRACT_PROJECT, project),
  // A cluster-admin's (recipes are admin-only): GET /api/recipes/run of a
  // run another updater pod runs, of a failed run with its ready clean-up
  // request, and POST /api/recipes/plan with problems.
  recipeRun: (): RecipeRunStatus => clone<RecipeRunStatus>(recipeRunJson),
  recipeRunEnded: (): RecipeRunStatus => clone<RecipeRunStatus>(recipeRunEndedJson),
  recipePlan: (): RecipePlan => clone<RecipePlan>(recipePlanJson),
};

// Compile-time checks: the generated JSON fits the frontend's types. A
// JSON import types its strings as string, so string unions ("admin" |
// "user") are widened to string here; any other difference (a field
// renamed, an object where the UI expects a string, a missing field) fails
// `tsc --noEmit`.
type Widen<T> = T extends string ? string : T extends (infer U)[] ? Widen<U>[] : T extends object ? { [K in keyof T]: Widen<T[K]> } : T;
const typed: {
  summary: Widen<ClusterSummary>;
  operation: Widen<UserOperationStatus>;
  permissions: Widen<UserPermissions>;
  project: Widen<ProjectStatus>;
  projectProblems: Widen<ProjectStatus>;
  playground: Widen<PlaygroundStatus>;
  playgroundProblem: Widen<PlaygroundStatus>;
  samples: Widen<MLflowSamplesStatus>;
  recipeRun: Widen<RecipeRunStatus>;
  recipeRunEnded: Widen<RecipeRunStatus>;
  recipePlan: Widen<RecipePlan>;
} = {
  summary: summaryJson,
  operation: operationUserJson,
  permissions: permissionsUserJson,
  project: projectStatusJson,
  projectProblems: projectStatusProblemsJson,
  playground: playgroundJson,
  playgroundProblem: playgroundProblemJson,
  samples: samplesJson,
  recipeRun: recipeRunJson,
  recipeRunEnded: recipeRunEndedJson,
  recipePlan: recipePlanJson,
};
void typed;
