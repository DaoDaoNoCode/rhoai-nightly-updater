package cluster

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// updateRBACGolden rewrites testdata/rbac-requests.golden from the source:
//
//	go test ./pkg/cluster -run TestRBACRequestsGolden -update
var updateRBACGolden = flag.Bool("update", false, "rewrite testdata/rbac-requests.golden")

const rbacGoldenFile = "testdata/rbac-requests.golden"

// The RBAC scanner's view of the package, frozen: every request it derives
// (verb, API group, resource, namespace and name, with how many times it is
// derived; no source positions, which change with any edit), the calls on
// c.Bookkeeping(), and the excluded call sites it met. A refactor that moves
// or rewrites API calls without changing what they request (REST helpers,
// the package split) must leave this file byte for byte the same; a change
// that does request something else regenerates it with -update, and the
// diff shows what the ServiceAccount now asks for.
func TestRBACRequestsGolden(t *testing.T) {
	got := rbacGolden(t)
	if *updateRBACGolden {
		if err := os.MkdirAll(filepath.Dir(rbacGoldenFile), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(rbacGoldenFile, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(rbacGoldenFile)
	if err != nil {
		t.Fatalf("%v (create it with -update)", err)
	}
	if got != string(want) {
		t.Fatalf("the RBAC scanner derives other requests than %s; if the change is meant to request something else, rerun with -update and review the diff:\n%s", rbacGoldenFile, lineDiff(string(want), got))
	}
}

func rbacGolden(t *testing.T) string {
	t.Helper()
	all, excluded := scanRequests(t, nil, false)
	books, _ := scanRequests(t, nil, true)
	var b strings.Builder
	b.WriteString("# Generated by TestRBACRequestsGolden (-update). Do not edit.\n")
	writeRequestCounts(&b, "requests", all)
	writeRequestCounts(&b, "bookkeeping requests", books)
	sites := make([]string, 0, len(excluded))
	for s := range excluded {
		sites = append(sites, s)
	}
	sort.Strings(sites)
	fmt.Fprintf(&b, "\n## excluded call sites (%d)\n", len(sites))
	for _, s := range sites {
		b.WriteString(s + "\n")
	}
	return b.String()
}

func writeRequestCounts(b *strings.Builder, title string, reqs []rbacRequest) {
	counts := map[string]int{}
	for _, r := range reqs {
		k := r.key()
		if r.NamedReview {
			k += " namedReview"
		}
		counts[k]++
	}
	keys := make([]string, 0, len(counts))
	for k := range counts {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(b, "\n## %s (%d derived, %d distinct)\n", title, len(reqs), len(keys))
	for _, k := range keys {
		fmt.Fprintf(b, "%d %s\n", counts[k], k)
	}
}

// lineDiff lists the lines only in want (-) and only in got (+).
func lineDiff(want, got string) string {
	count := func(s string) map[string]int {
		m := map[string]int{}
		for l := range strings.SplitSeq(s, "\n") {
			m[l]++
		}
		return m
	}
	w, g := count(want), count(got)
	var out []string
	for l, n := range w {
		for range n - g[l] {
			out = append(out, "- "+l)
		}
	}
	for l, n := range g {
		for range n - w[l] {
			out = append(out, "+ "+l)
		}
	}
	sort.Strings(out)
	return strings.Join(out, "\n")
}
